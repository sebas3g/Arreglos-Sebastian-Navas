public class Ejercicio1 {
    public static void main(String[] args) {

        int[] edades = {18, 21, 19, 25, 30};

        // Imprimir primer elemento
        System.out.println("Primer elemento: " + edades[0]);

        // Cambiar el índice 2 por 22
        edades[2] = 22;

        // Mostrar último elemento
        System.out.println("Ultimo elemento: " + edades[edades.length - 1]);
    }
}
